/** União com os 66 slugs válidos: 'genesis' | 'exodo' | ... | 'apocalipse'. */
export type BookSlug = (typeof BOOK_ROWS)[number][0];

function toBook(row: BookRow, index: number): BibleBook {
  const [
    slug,
    name,
    abbreviation,
    transliteration,
    originalName,
    division,
    chapters,
    traditionalAuthor,
    theme,
  ] = row;

  const order = toCanonicalOrder(index + 1);
  const testament: Testament = order <= LAST_OLD_TESTAMENT_ORDER ? 'old' : 'new';

  return {
    slug,
    order,
    name,
    abbreviation,
    transliteration,
    originalName,
    language: testament === 'old' ? 'hebrew' : 'greek',
    testament,
    division,
    chapters,
    traditionalAuthor,
    theme,
  };
}

export const BIBLE_BOOKS: readonly BibleBook[] = BOOK_ROWS.map(toBook);
export const TOTAL_CHAPTERS = BIBLE_BOOKS.reduce((sum, book) => sum + book.chapters, 0);
